def addition(a, b):
    """Return a + b."""
    return a + b

def subtraction(a, b):
    """Return a - b."""
    return a - b

def multiplication(a, b):
    """Return a * b."""
    return a * b

def division(a, b):
    """Return a / b."""
    return a / b

print(addition(5, 3))
print(subtraction(5, 3))
print(multiplication(5, 3))
print(division(10, 2))
